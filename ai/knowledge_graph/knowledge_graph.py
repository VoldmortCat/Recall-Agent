def build_knowledge_nodes():
    """
    将预置知识图谱转换为扁平的知识点节点列表
    适用于导入数据库
    """
    nodes = []
    for subject, chapters in KNOWLEDGE_GRAPH.items():
        for chapter, topics in chapters.items():
            for topic in topics:
                nodes.append({
                    "name": topic,
                    "subject": subject,
                    "chapter": chapter,
                })
    return nodes


def get_subject_knowledge(subject: str) -> list:
    """获取指定学科的所有知识点"""
    nodes = build_knowledge_nodes()
    return [n for n in nodes if n["subject"] == subject]


